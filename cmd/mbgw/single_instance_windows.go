//go:build windows

package main

import (
	"fmt"
	"unsafe"

	"golang.org/x/sys/windows"
)

// mbgwSingleInstanceMutexName — имя именованного Windows-мьютекса для
// защиты от одновременного запуска двух экземпляров mbgw.exe (добавлено
// 2026-08-30, прямой запрос оператора — после появления службы Windows
// стало ДВА способа запустить один и тот же процесс: службой и вручную
// из консоли. Если случайно запустить оба одновременно — оба экземпляра
// начнут опрашивать одни и те же COM-порты/IP-адреса приборов
// параллельно, мешая друг другу физически на линии связи (та же беда,
// что мы весь день лечили ВНУТРИ одного процесса через internal/lease,
// только теперь уже МЕЖДУ двумя разными процессами — internal/lease
// живёт в памяти одного процесса и ничего не знает про другой), плюс
// конфликт за порт веб-интерфейса и одновременная запись в один лог-файл
// и в один файл БД.
//
// "Global\" в начале имени — мьютекс, видимый во ВСЕХ сессиях
// пользователей Windows, а не только в текущей: служба Windows обычно
// работает в отдельной, служебной сессии (Session 0), отличной от
// сессии залогиненного администратора, который может запустить второй
// экземпляр вручную из своей PowerShell — без "Global\" эти две сессии
// видели бы РАЗНЫЕ, не связанные друг с другом мьютексы, и защита
// просто не сработала бы для самого главного сценария (служба +
// ручной запуск одновременно).
const mbgwSingleInstanceMutexName = `Global\mbgw_single_instance`

// mbgwMutexSDDL — дескриптор безопасности для мьютекса, в виде строки
// SDDL: "разрешить полный доступ (GA) всем (WD — well-known SID
// 'Everyone')". ИСПРАВЛЕНО (2026-08-30, найдено оператором живьём):
// без явного дескриптора CreateMutex использует дескриптор ПО
// УМОЛЧАНИЮ, который для мьютекса, созданного службой (работает от
// имени LocalSystem, в изолированной Session 0), НЕ даёт доступа
// процессу, запущенному вручную от имени обычного администратора (уже
// другая сессия/учётная запись) — CreateMutex падал с "Access is
// denied", защита молча не срабатывала, и оба процесса благополучно
// стартовали параллельно, ровно то, чего эта защита должна была не
// допустить. "Global\" в имени решает только видимость ЧЕРЕЗ сессии,
// но не права доступа МЕЖДУ разными учётными записями — это два
// разных, независимых требования Windows, оба нужны одновременно.
const mbgwMutexSDDL = "D:(A;;GA;;;WD)"

// acquireSingleInstanceLock пытается захватить именованный
// Windows-мьютекс. Если он уже удерживается ДРУГИМ процессом (то есть
// mbgw.exe уже где-то работает — неважно, запущен ли он службой или
// вручную) — возвращает ok=false, и вызывающий код должен немедленно
// завершиться с понятной ошибкой, а не тихо создавать конфликтующий
// второй процесс.
//
// Мьютекс НЕ освобождается явно нигде в коде — Windows сама освобождает
// его, когда процесс-владелец завершается (штатно или аварийно, не
// важно) — это стандартный, надёжный способ в Windows проверить "уже ли
// где-то работает экземпляр этой программы", не требующий отдельной
// логики очистки при неожиданном падении процесса.
func acquireSingleInstanceLock() (ok bool, err error) {
	namePtr, err := windows.UTF16PtrFromString(mbgwSingleInstanceMutexName)
	if err != nil {
		return false, fmt.Errorf("не удалось подготовить имя мьютекса: %w", err)
	}

	sd, err := windows.SecurityDescriptorFromString(mbgwMutexSDDL)
	if err != nil {
		return false, fmt.Errorf("не удалось построить дескриптор безопасности мьютекса: %w", err)
	}
	sa := &windows.SecurityAttributes{
		Length:             uint32(unsafe.Sizeof(windows.SecurityAttributes{})),
		SecurityDescriptor: sd,
		InheritHandle:      0,
	}

	_, err = windows.CreateMutex(sa, false, namePtr)
	if err == windows.ERROR_ALREADY_EXISTS {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("не удалось создать мьютекс блокировки: %w", err)
	}
	return true, nil
}
